import streamlit as st
import pandas as pd
import altair as alt

st.set_page_config(
    page_title="Аудит качества: Английский язык",
    page_icon="📊",
    layout="centered"
)

st.title("📊 Аудит качества подготовки")
st.subheader("Честный самоанализ по английскому языку (9 класс)")
st.markdown(
    "Оцени свои усилия за последний месяц по шкале от **1** до **10** "
    "(1 — *вообще не делал*, 10 — *делал идеально*). Будь честен с собой — "
    "эти баллы не идут в журнал, они нужны для твоего личного плана."
)

st.divider()

col_info1, col_info2 = st.columns(2)
with col_info1:
    student_name = st.text_input("Имя и фамилия (или ник)", placeholder="Например: Алексей И.")
with col_info2:
    student_class = st.text_input("Класс", value="9-5")

st.markdown("### 🏠 Блок 1. Домашняя работа и самоподготовка")
q1 = st.slider(
    "1. Регулярность выполнения ДЗ (делаю сам и вовремя или списываю перед уроком?)",
    1, 10, 5
)
q2 = st.slider(
    "2. Качество работы с новыми словами (учу через карточки/Quizlet или угадываю на диктанте?)",
    1, 10, 5
)
q3 = st.slider(
    "3. Самостоятельный разбор трудных тем (открываю справочник/видеоразбор, если не понял правило?)",
    1, 10, 5
)
q4 = st.slider(
    "4. Управление временем (выделяю ли хотя бы 30 минут дома перед каждым уроком?)",
    1, 10, 5
)

screen_time = st.number_input(
    "📱 Посмотри в телефоне: сколько часов за вчера составило твоё «Экранное время» в соцсетях/играх?",
    min_value=0.0, max_value=24.0, value=3.5, step=0.5
)

st.markdown("### 🏫 Блок 2. Работа на уроке")
q5 = st.slider(
    "5. Внимательность и фокус (слушаю объяснения или отвлекаюсь на телефон/соседа?)",
    1, 10, 5
)
q6 = st.slider(
    "6. Активность на уроке (поднимаю руку, участвую в устной работе класса?)",
    1, 10, 5
)
q7 = st.slider(
    "7. Инициатива при трудностях (задаю вопрос учителю, если тема непонятна?)",
    1, 10, 5
)

st.markdown("### 🎯 Блок 3. Практика и работа над ошибками")
q8 = st.slider(
    "8. Системная тренировка форматов ОГЭ (прорешиваю типовые задания дополнительно?)",
    1, 10, 5
)
q9 = st.slider(
    "9. Работа над ошибками (разбираю ошибки после диктантов и тестов?)",
    1, 10, 5
)
q10 = st.slider(
    "10. Языковая практика вне учебника (видео, песни, подкасты, игры на английском?)",
    1, 10, 5
)

st.markdown("### ⚖️ Блок 4. Самооценка")
col_self1, col_self2 = st.columns(2)
with col_self1:
    self_effort = st.slider("На сколько из 10 ты сам оцениваешь свои общие усилия?", 1, 10, 5)
with col_self2:
    deserved_grade = st.radio("Какую оценку ты честно заслуживаешь?", [2, 3, 4, 5], horizontal=True, index=1)

st.divider()

if st.button("🚀 Рассчитать мой индекс качества", type="primary", use_container_width=True):
    block1 = q1 + q2 + q3 + q4
    block2 = q5 + q6 + q7
    block3 = q8 + q9 + q10
    total_score = block1 + block2 + block3

    st.header(f"Результаты аудита{f': {student_name}' if student_name else ''}")

    m1, m2, m3 = st.columns(3)
    m1.metric("Индекс качества", f"{total_score} / 100")
    m2.metric("Экранное время (вчера)", f"{screen_time} ч.")
    m3.metric("Цель на английский", "0.5 ч. (30 мин)")

    if total_score < 50:
        st.error(
            f"🔴 **Красная зона риска ({total_score} баллов).** "
            "Текущие трудности с оценками напрямую связаны с дефицитом регулярной практики. "
            "Хорошая новость: чтобы выйти из зоны риска, не нужно учить язык часами — достаточно 30 минут по четкому плану."
        )
    elif total_score < 75:
        st.warning(
            f"🟡 **Желтая зона нестабильного результата ({total_score} баллов).** "
            "Ты прикладываешь усилия, но действуешь хаотично. Закрыв 2–3 самых слабых пункта ниже, "
            "ты легко выйдешь на стабильные «4» и «5»."
        )
    else:
        st.success(
            f"🟢 **Зеленая зона устойчивого качества ({total_score} баллов).** "
            "Отличный уровень самоорганизации! Если при таком высоком балле оценки всё ещё ниже ожидаемых — "
            "покажи этот экран учителю, чтобы подобрать индивидуальный маршрут поддержки."
        )

    if screen_time > 2.5 and total_score < 75:
        st.info(
            f"💡 **Заметка по времени:** Вчера в телефоне прошло **{screen_time} ч.**, а на английский "
            "нужно всего **0.5 ч. (30 минут)** — это меньше 15% твоего экранного времени."
        )

    # График по 10 критериям с подсветкой зон риска
    criteria_names = [
        "1. Регулярность ДЗ",
        "2. Работа со словами",
        "3. Разбор правил",
        "4. Тайм-менеджмент (30 мин)",
        "5. Фокус на уроке",
        "6. Активность в классе",
        "7. Вопросы учителю",
        "8. Тренировка ОГЭ",
        "9. Работа над ошибками",
        "10. Практика вне учебника"
    ]
    scores = [q1, q2, q3, q4, q5, q6, q7, q8, q9, q10]

    def get_zone(val):
        if val <= 4:
            return "Зона риска (1–4)"
        elif val <= 7:
            return "Нестабильно (5–7)"
        else:
            return "Устойчиво (8–10)"

    df_chart = pd.DataFrame({
        "Критерий": criteria_names,
        "Балл": scores,
        "Статус": [get_zone(s) for s in scores]
    })

    st.subheader("📈 Профиль твоих учебных привычек")
    chart = alt.Chart(df_chart).mark_bar(cornerRadiusEnd=4).encode(
        x=alt.X("Балл:Q", scale=alt.Scale(domain=[0, 10]), title="Баллы (из 10)"),
        y=alt.Y("Критерий:N", sort=None, title=""),
        color=alt.Color(
            "Статус:N",
            scale=alt.Scale(
                domain=["Зона риска (1–4)", "Нестабильно (5–7)", "Устойчиво (8–10)"],
                range=["#e74c3c", "#f39c12", "#27ae60"]
            ),
            legend=alt.Legend(orient="bottom", title="")
        ),
        tooltip=["Критерий", "Балл", "Статус"]
    ).properties(height=360)

    st.altair_chart(chart, use_container_width=True)

    # Генерация 3 персональных шагов по самым слабым пунктам
    st.subheader("📝 Твой личный план действий (30 минут в день)")
    advice_map = {
        "1. Регулярность ДЗ": "Делай домашнее задание в день получения (пока свежи объяснения) — это займет на 40% меньше времени.",
        "2. Работа со словами": "Учи новую лексику интервалами по 10 минут через карточки (Quizlet / бумажные стикеры) вслух.",
        "3. Разбор правил": "Если правило непонятно — посмотри 5-минутный видеоразбор или схему в справочнике до выполнения упражнений.",
        "4. Тайм-менеджмент (30 мин)": "Ставь таймер ровно на 30 минут без телефона (режим «Не беспокоить»): 10 мин слова + 20 мин практика.",
        "5. Фокус на уроке": "Убирай телефон в рюкзак на 40 минут урока: 80% материала запоминается прямо в классе.",
        "6. Активность в классе": "Поставь цель ответить минимум 2 раза за каждый урок — это страхует от внезапных плохих оценок.",
        "7. Вопросы учителю": "Выписывай на полях тетради 1 вопрос по непонятной теме и задавай его в конце урока.",
        "8. Тренировка ОГЭ": "Решай по 1 мини-блоку ОГЭ (например, одно аудирование или один текст) 3 раза в неделю.",
        "9. Работа над ошибками": "Заведи «Тетрадь ловушек»: выписывай туда слова и правила, в которых ошибся на диктанте.",
        "10. Практика вне учебника": "Переведи интерфейс телефона на английский или смотри 1 короткое видео на английском с субтитрами в день."
    }

    sorted_items = sorted(zip(criteria_names, scores), key=lambda x: x[1])
    top_3_weak = sorted_items[:3]

    for idx, (crit, val) in enumerate(top_3_weak, start=1):
        st.markdown(f"**Шаг {idx} (усиливаем «{crit}», сейчас {val}/10):** {advice_map[crit]}")

    # Текст для копирования/отчета
    report_text = (
        f"Аудит качества (Английский язык) | Ученик: {student_name or 'Аноним'} ({student_class})\n"
        f"Общий индекс: {total_score}/100 | Экранное время: {screen_time} ч. | Самооценка: {deserved_grade}\n"
        f"Точки роста: {', '.join([f'{c} ({v}/10)' for c, v in top_3_weak])}"
    )
    st.text_area("📋 Скопируй итог для отчета или дневника самонаблюдения:", report_text, height=100)
